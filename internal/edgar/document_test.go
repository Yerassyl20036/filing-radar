func TestTextInlineXBRL(t *testing.T) {
	got, err := Text(strings.NewReader(inlineXBRL8K), "text/html")
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"UNITED STATES\nSECURITIES AND EXCHANGE COMMISSION\nWashington, D.C. 20549\nFORM 8-K",
		"California | 001-36743 | 94-2404110",
		"(State or other jurisdiction of incorporation) | (Commission File Number) | (I.R.S. Employer Identification No.)",
		"Item 2.02 Results of Operations and Financial Condition.\n" +
			"On October 30, 2026, Apple Inc. (“Apple”) issued a press release regarding Apple’s financial results for its fourth fiscal quarter ended September 26, 2026. " +
			"A copy of Apple’s press release is attached hereto as Exhibit 99.1.",
		"The information in this Item 2.02 and in Exhibit 99.1 shall not be deemed “filed”.",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %q", want)
		}
	}
	// Machine-only facts, markup and anything else a reader doesn't see.
	for _, gone := range []string{"0000320193", "2026-10-30", "false", "aapl-20261030", "Helvetica", "tracking", "filing agent", "Page footer", "<", "\u00a0", "\n\n\n"} {
		if strings.Contains(got, gone) {
			t.Errorf("output contains %q", gone)
		}
	}
	if t.Failed() {
		t.Logf("output:\n%s", got)
	}
}

type textCase struct {
	name, contentType, in, want string
}

func checkText(t *testing.T, cases []textCase) {
	t.Helper()
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got, err := Text(strings.NewReader(tc.in), tc.contentType)
			if err != nil {
				t.Fatal(err)
			}
			if got != tc.want {
				t.Errorf("got  %q\nwant %q", got, tc.want)
			}
		})
	}
}

func TestTextHTML(t *testing.T) {
	checkText(t, []textCase{
		{"paragraphs leave a blank line", "text/html", "<html><body><p>One</p><p>Two</p>", "One\n\nTwo"},
		{"divs and breaks end lines", "text/html", "<html><body><div>a<br>b</div><div>c</div>", "a\nb\nc"},
		{"source newlines are just spaces", "text/html", "<body><p>\n  Several\n   words\n</p>", "Several words"},
		{"entities", "text/html", "<body><p>AT&amp;T&#8217;s&nbsp;&nbsp;deal &#146;</p>", "AT&T’s deal ’"},
		// SEC tables put "$" and ")" in cells of their own and pad with
		// empty columns; only cells with text get a separator.
		{"table", "text/html", `<body><table>
			<tr><td>Revenue</td><td></td><td>$</td><td>1,234</td><td></td></tr>
			<tr><td></td><td>Net income</td><td>$</td><td>567</td></tr></table>`,
			"Revenue | $ | 1,234\nNet income | $ | 567"},
		{"blocks inside cells stay on the row", "text/html",
			"<body><table><tr><td><p>Item 2.02</p></td><td><div>Results<br/>of Operations</div></td></tr></table>",
			"Item 2.02 | Results of Operations"},
		{"hidden element with hidden children", "text/html",
			`<body><div style="DISPLAY : NONE"><div>x</div><div>y</div></div><p>shown</p>`, "shown"},
		{"a hidden void element hides only itself", "text/html",
			`<body><p>one<img style="display:none" src="x.png">two</p>`, "onetwo"},
		{"pre keeps its lines", "text/html",
			"<body><pre>Line one\n  Line   two\n\n\n\nLine three</pre><p>after</p>", "Line one\nLine two\n\nLine three\n\nafter"},
		{"missing </head>", "text/html", "<html><head><title>t</title><body><p>text</p>", "text"},
		// The tokenizer, like a browser, reads past <script/> to </script>.
		{"self-closed script", "text/html", `<body><p>a</p><script/>var x = "<p>no</p>";</script><p>b</p>`, "a\n\nb"},
		{"zero-width characters", "text/html", "<body><p>\ufeffword\u200bs</p>", "words"},
	})
}

func TestTextCharsets(t *testing.T) {
	checkText(t, []textCase{
		{"windows-1252 without a charset", "text/html",
			"<html><body><p>Apple\x92s \x93results\x94 \x96 caf\xe9</p></body></html>", "Apple’s “results” – café"},
		{"ISO-8859-1 in the Content-Type", "text/html; charset=ISO-8859-1",
			"<html><body><p>Soci\xe9t\xe9 G\xe9n\xe9rale</p></body></html>", "Société Générale"},
		// The first KB is ASCII, so a 1 KB sniff would guess windows-1252
		// and turn ’ into â€™.
		{"UTF-8 past the first KB", "text/html",
			"<html><body><!--" + strings.Repeat("x", 2000) + "--><p>Apple’s</p></body></html>", "Apple’s"},
		{"a <meta> that wrongly claims UTF-8", "text/html",
			`<html><head><meta charset="utf-8"></head><body><p>Apple` + "\x92" + `s</p></body></html>`, "Apple’s"},
		{"windows-1252 plain text", "text/plain", "Apple\x92s results\n", "Apple’s results"},
	})
}

func TestTextPlain(t *testing.T) {
	checkText(t, []textCase{
		{"text/plain", "text/plain; charset=us-ascii",
			"  ITEM 2.02.\tRESULTS   OF OPERATIONS  \r\n\r\n\r\n\r\n   On October 30, 2026, the Company\r\nissued a press release.\r\n",
			"ITEM 2.02. RESULTS OF OPERATIONS\n\nOn October 30, 2026, the Company\nissued a press release."},
		// Old ASCII filings use SGML-ish tags, which aren't HTML.
		{"no <html> or <body>", "", "<PAGE>  1\n\n\n<TABLE>\nITEM 8.01   OTHER EVENTS\n</TABLE>",
			"<PAGE> 1\n\n<TABLE>\nITEM 8.01 OTHER EVENTS\n</TABLE>"},
		{"text/plain wins over markup", "text/plain", "<html> is how a page starts.", "<html> is how a page starts."},
		{"empty", "text/html", "", ""},
		{"only whitespace", "text/plain", " \n\t\r\n ", ""},
	})
}

func TestTextReadError(t *testing.T) {
	boom := errors.New("connection reset")
	if _, err := Text(iotest.ErrReader(boom), "text/html"); !errors.Is(err, boom) {
		t.Errorf("err = %v, want the read error", err)
	}
}

func TestDocument(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if got := r.Header.Get("User-Agent"); got != testAgent {
			t.Errorf("User-Agent = %q", got)
		}
		if r.URL.Path != "/Archives/edgar/data/320193/000032019326000101/aapl-8k.htm" {
			http.NotFound(w, r)
			return
		}
		// Undeclared windows-1252, as SEC serves many pages, so the
		// Content-Type has to reach Text.
		w.Header().Set("Content-Type", "text/html")
		_, _ = w.Write([]byte("<html><body><p>Apple\x92s results</p></body></html>"))
	}))
	defer srv.Close()
	c, err := NewClient(Config{BaseURL: srv.URL, UserAgent: testAgent})
	if err != nil {
		t.Fatal(err)
	}
	ctx := context.Background()

	got, err := c.Document(ctx, "0000320193", "0000320193-26-000101", "aapl-8k.htm")
	if err != nil || got != "Apple’s results" {
		t.Fatalf("Document = %q, %v", got, err)
	}
	var se *StatusError
	if _, err := c.Document(ctx, "0000320193", "0000320193-26-000101", "missing.htm"); !errors.As(err, &se) || se.Code != http.StatusNotFound {
		t.Errorf("missing document: err = %v, want a 404 StatusError", err)
	}
}
